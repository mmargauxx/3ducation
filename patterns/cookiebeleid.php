<p>Deze pagina legt uit welke cookies en gelijkaardige technieken 3DUCATION.be gebruikt, waarvoor, en hoe je zelf bepaalt wat je toelaat. Dit cookiebeleid hoort bij onze <a href="/privacyverklaring">privacyverklaring</a>.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Wat zijn cookies?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Cookies zijn kleine tekstbestanden die een website op je toestel bewaart. Sommige zijn nodig om de site te laten werken (bijvoorbeeld om je winkelmandje te onthouden). Andere helpen ons te begrijpen hoe de site gebruikt wordt. Voor die laatste vragen we eerst je toestemming, zoals de Belgische en Europese regels (GDPR en de wet elektronische communicatie) voorschrijven. Naast cookies gebruiken we ook <em>localStorage</em>, een geheugen in je browser dat op dezelfde manier werkt.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Je keuze</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Bij je eerste bezoek zie je een cookiebanner. Daar kies je “Alles aanvaarden”, “Alles weigeren” of je kiest zelf per categorie. Zonder keuze plaatsen we alleen noodzakelijke cookies. Je keuze bewaren we 6 maanden in de cookie <code>3ducation_cookie_consent</code>; daarna vragen we het opnieuw. Je kunt je keuze op elk moment aanpassen of intrekken via <a href="#cookie-instellingen" data-cookie-settings>Cookie-instellingen</a> (ook onderaan elke pagina). Intrekken is even eenvoudig als toestemmen.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Noodzakelijke cookies</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Deze zijn nodig om de site en de webshop te laten werken. Ze plaatsen geen profiel van jou en worden niet gedeeld met adverteerders. Je kunt ze niet uitschakelen.</p>
